/**
 * Mirrors JobWing's src/core/humanize.ts (stock phrases, sentence rhythm, em dashes, AI wording, hidden characters).
 * Rules, not a trained detector: they remove the habits that make a text read as machine-written. Kept in step with the
 * desktop app so a résumé is judged the same way wherever it was made.
 */
const CLICHES = [
  'spearheaded', 'leveraged', 'leverage', 'synergy', 'synergize', 'results-driven', 'results driven', 'detail-oriented', 'detail oriented', 'passionate about',
  'proven track record', 'dynamic', 'cutting-edge', 'cutting edge', 'seamlessly', 'robust', 'holistic', 'delve', 'tapestry', 'testament', "in today's fast-paced",
  'fast-paced environment', 'i am thrilled', 'i am excited to', 'game-changer', 'game changer', 'think outside the box', 'go-getter', 'self-starter', 'team player',
  'orchestrated', 'meticulous', 'unwavering', 'tireless', 'harnessed', 'utilized', 'utilize', 'facilitated', 'streamlined', 'plethora', 'myriad', 'realm', 'landscape',
  'ever-evolving', 'ever evolving', 'elevate', 'unlock', 'empower', 'pivotal', 'furthermore', 'moreover', 'in conclusion', 'embark', 'beacon', 'keen eye',
];

export interface TextCheck {
  /** 0 reads human, 100 reads machine-written. */
  aiLikeness: number;
  verdict: 'reads natural' | 'a few machine-like habits' | 'reads machine-written';
  signals: string[];
  flaggedPhrases: string[];
  stats: { sentences: number; words: number; avgSentenceWords: number; sentenceVariation: number; numbersPerHundredWords: number };
  edits: string[];
}

/**
 * Wording that gives away where a text came from, or that nobody writes in a résumé. A word is listed only when the user's own résumé does
 * not already contain it (a person who really built a "Gemini API" project may say so).
 */
const AI_MARKERS = [
  'as an ai', 'language model', 'chatgpt', 'gpt-4', 'gpt-5', 'openai', 'anthropic', 'claude', 'gemini', 'copilot', 'generated by', 'ai-generated', 'ai generated',
  'written by ai', 'made by ai', 'here is your', "here's your", 'here is the', 'certainly!', 'i hope this', 'feel free to', 'lorem ipsum', 'placeholder', '[your', '[company', '[name', '[insert',
];

/** Characters you cannot see (zero-width, direction marks, soft hyphens, byte-order marks). Some tools add them, and some parsers notice them. */
const INVISIBLE = new RegExp("[\u200b-\u200f\u2028\u2029\u202a-\u202e\u2060-\u2064\u00ad\ufeff]", "g");

export function aiMarkers(text: string, original = ''): string[] {
  const lower = text.toLowerCase();
  const base = original.toLowerCase();
  return AI_MARKERS.filter((m) => lower.includes(m) && !base.includes(m));
}

export function invisibleCharacters(text: string): number {
  return (text.match(INVISIBLE) ?? []).length;
}

/** Remove the invisible characters. Everything else stays exactly as written. */
export function stripInvisible(text: string): string {
  return text.replace(INVISIBLE, '');
}

const words = (s: string) => s.toLowerCase().match(/[a-z0-9+#.']+/g) ?? [];

export function checkText(text: string): TextCheck {
  const sentences = text
    .split(/(?<=[.!?])\s+|\n+/)
    .map((s) => s.trim())
    .filter((s) => words(s).length >= 3);
  const lens = sentences.map((s) => words(s).length);
  const w = words(text);
  const mean = lens.reduce((a, b) => a + b, 0) / Math.max(1, lens.length);
  const sd = Math.sqrt(lens.reduce((a, b) => a + (b - mean) ** 2, 0) / Math.max(1, lens.length));
  const variation = mean ? sd / mean : 0;
  const lower = text.toLowerCase();
  const flagged = Array.from(new Set(CLICHES.filter((c) => lower.includes(c))));
  const dashes = (text.match(/—/g) ?? []).length;
  const nums = (text.match(/\b\d[\d,.]*%?/g) ?? []).length;
  const numRate = (nums / Math.max(1, w.length)) * 100;
  const startCounts = new Map<string, number>();
  for (const s of sentences) {
    const first = words(s)[0] ?? '';
    startCounts.set(first, (startCounts.get(first) ?? 0) + 1);
  }
  const topStart = Array.from(startCounts.entries()).sort((a, b) => b[1] - a[1])[0];

  let score = 15;
  const signals: string[] = [];
  const edits: string[] = [];
  if (flagged.length) {
    score += Math.min(40, flagged.length * 7);
    signals.push(`${flagged.length} stock phrase${flagged.length > 1 ? 's' : ''} common in machine text.`);
    edits.push(`Replace or cut: ${flagged.slice(0, 8).join(', ')}. Say what you did in plain words (built, ran, fixed, cut, wrote).`);
  }
  if (lens.length >= 5 && variation < 0.3) {
    score += 15;
    signals.push('Sentences are all about the same length, which reads robotic.');
    edits.push('Mix short and long sentences. Let one sentence be five words.');
  }
  if (topStart && sentences.length >= 6 && topStart[1] / sentences.length > 0.35) {
    score += 10;
    signals.push(`${Math.round((topStart[1] / sentences.length) * 100)}% of sentences start with "${topStart[0]}".`);
    edits.push(`Vary how lines start; many begin with "${topStart[0]}".`);
  }
  if (dashes >= 1) {
    score += dashes >= 3 ? 12 : 8;
    signals.push(`${dashes} em dash${dashes > 1 ? 'es' : ''}, a common machine habit.`);
    edits.push('Replace every em dash with a comma, a full stop or a plain hyphen.');
  }
  if (w.length >= 80 && numRate < 1.2) {
    score += 12;
    signals.push('Few numbers or specifics. Real experience has figures, tools and names.');
    edits.push('Add real numbers that are already true from your résumé (users, %, time saved, rows, requests).');
  }
  score = Math.max(0, Math.min(100, score));
  return {
    aiLikeness: score,
    verdict: score < 35 ? 'reads natural' : score < 60 ? 'a few machine-like habits' : 'reads machine-written',
    signals,
    flaggedPhrases: flagged,
    stats: { sentences: sentences.length, words: w.length, avgSentenceWords: Math.round(mean * 10) / 10, sentenceVariation: Math.round(variation * 100) / 100, numbersPerHundredWords: Math.round(numRate * 10) / 10 },
    edits,
  };
}

const STOP = new Set('a an the and or of to in for with on at by from as is are be this that these those you your we our will can able have has had it its their they them who which what when where how not but if than then also more most such any all per etc'.split(' '));

/** How many of the job's key terms the résumé already contains (what an ATS keyword filter looks at). */
export function keywordCoverage(resume: string, jobDescription: string) {
  const jd = words(jobDescription).filter((t) => t.length > 2 && !STOP.has(t));
  const freq = new Map<string, number>();
  for (const t of jd) freq.set(t, (freq.get(t) ?? 0) + 1);
  const key = Array.from(freq.entries()).sort((a, b) => b[1] - a[1]).slice(0, 40).map(([t]) => t);
  const have = new Set(words(resume));
  const hit = key.filter((k) => have.has(k));
  const missing = key.filter((k) => !have.has(k));
  return { coverage: key.length ? Math.round((hit.length / key.length) * 100) : 0, matched: hit, missing: missing.slice(0, 20), note: 'Add a missing term only where it is true for you and your résumé already shows the work.' };
}
